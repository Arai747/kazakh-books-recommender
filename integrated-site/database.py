
"""BookRec — SQLite және PostgreSQL деректер базасы."""

import os
import sqlite3
from pathlib import Path
from contextlib import contextmanager

DB_PATH = Path(__file__).parent / "bookrec.db"


def get_database_url():
    """Streamlit secrets немесе орта айнымалысынан URL алу."""
    url = os.environ.get("DATABASE_URL")

    if url:
        return url

    try:
        import streamlit as st
        return st.secrets.get("DATABASE_URL", "")
    except (ImportError, FileNotFoundError, KeyError):
        return ""


def is_postgres():
    url = get_database_url()
    return url.startswith(("postgresql://", "postgres://"))


@contextmanager
def get_connection():
    """Базамен қауіпсіз байланыс орнату."""
    if is_postgres():
        import psycopg
        conn = psycopg.connect(get_database_url())
    else:
        conn = sqlite3.connect(DB_PATH)

    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db():
    """Қажетті кестелерді жасау."""
    with get_connection() as conn:
        if is_postgres():
            conn.execute("""
                CREATE TABLE IF NOT EXISTS reading_list (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY
                        PRIMARY KEY,
                    user_id TEXT NOT NULL,
                    book_id INTEGER NOT NULL,
                    added_at TIMESTAMPTZ DEFAULT NOW(),
                    UNIQUE(user_id, book_id)
                )
            """)
            conn.execute("""
                CREATE TABLE IF NOT EXISTS access_codes (
                    user_id TEXT PRIMARY KEY,
                    created_at TIMESTAMPTZ DEFAULT NOW()
                )
            """)
        else:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS reading_list (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    user_id TEXT NOT NULL,
                    book_id INTEGER NOT NULL,
                    added_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE(user_id, book_id)
                )
            """)
            conn.execute("""
                CREATE TABLE IF NOT EXISTS access_codes (
                    user_id TEXT PRIMARY KEY,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """)


def register_access_code(user_id):
    """Жаңа жеке кодты базаға тіркеу."""
    with get_connection() as conn:
        if is_postgres():
            conn.execute("""
                INSERT INTO access_codes (user_id)
                VALUES (%s)
                ON CONFLICT (user_id) DO NOTHING
            """, (user_id,))
        else:
            conn.execute("""
                INSERT OR IGNORE INTO access_codes (user_id)
                VALUES (?)
            """, (user_id,))


def access_code_exists(user_id):
    """Кодтың тіркелгенін тексеру."""
    with get_connection() as conn:
        placeholder = "%s" if is_postgres() else "?"
        row = conn.execute(
            f"SELECT 1 FROM access_codes WHERE user_id = {placeholder}",
            (user_id,)
        ).fetchone()
        return row is not None


def add_to_reading_list(user_id, book_id):
    """Кітапты таңдаулыларға қосу."""
    with get_connection() as conn:
        if is_postgres():
            conn.execute("""
                INSERT INTO reading_list (user_id, book_id)
                VALUES (%s, %s)
                ON CONFLICT (user_id, book_id) DO NOTHING
            """, (user_id, book_id))
        else:
            conn.execute("""
                INSERT OR IGNORE INTO reading_list (user_id, book_id)
                VALUES (?, ?)
            """, (user_id, book_id))


def remove_from_reading_list(user_id, book_id):
    """Кітапты таңдаулылардан өшіру."""
    with get_connection() as conn:
        placeholder = "%s" if is_postgres() else "?"
        conn.execute(
            f"""
            DELETE FROM reading_list
            WHERE user_id = {placeholder}
              AND book_id = {placeholder}
            """,
            (user_id, book_id)
        )


def get_reading_list(user_id):
    """Пайдаланушының таңдаулы кітаптарын алу."""
    with get_connection() as conn:
        placeholder = "%s" if is_postgres() else "?"
        rows = conn.execute(
            f"""
            SELECT book_id
            FROM reading_list
            WHERE user_id = {placeholder}
            ORDER BY added_at DESC, id DESC
            """,
            (user_id,)
        ).fetchall()

    return [row[0] for row in rows]
